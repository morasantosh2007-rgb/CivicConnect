def get_localized_scheme_attributes(title: str, language: str) -> Dict[str, str]:
    """Returns localized title, department, category, target, and benefits for any scheme."""
    lang = language if language in ["hi", "ta", "kn", "te", "en"] else "en"
    scheme = SCHEME_LOCALIZATION.get(title)
    if not scheme:
        return {}
    
    return {
        "title": scheme["title"].get(lang, scheme["title"]["en"]),
        "department": scheme["department"].get(lang, scheme["department"]["en"]),
        "category": scheme["category"].get(lang, scheme["category"]["en"]),
        "affected_citizens": scheme["affected_citizens"].get(lang, scheme["affected_citizens"]["en"]),
        "deadline": scheme["deadline"].get(lang, scheme["deadline"]["en"]),
        "benefits_description": scheme["benefits_description"].get(lang, scheme["benefits_description"]["en"])
    }
